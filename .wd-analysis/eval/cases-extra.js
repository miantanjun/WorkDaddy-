/* 评测集扩充（第二批）—— 目标：把「算不出显著性」这个瓶颈打掉
 *
 * 为什么必须扩：
 *   上一轮（阶段 7 侦查）所有结论都卡在同一处 —— 31 道正例，
 *   任何 2~5 题的差异都进不了显著区间（McNemar p=0.0923）。
 *   这不是统计方法问题，是样本量问题。要判断「新鲜度换位值不值 9.7pp」，
 *   必须有足够多的题把噪声压下去。
 *
 * 本批增补的重点是**原题集里完全没有的四类**：
 *
 *   ① 时效成对题（temporal-pair）—— 最要害的一类
 *      同一指标（回归套件数）在会话里被反复记录，值随时间单调增长。
 *      于是可以造一对**孪生题**：
 *        问「最新/现在是多少」 ⇒ 正确 gold = 最新的那行（检验新鲜度的收益）
 *        问「一开始/最早是多少」⇒ 正确 gold = 最早的那行（检验新鲜度的代价）
 *      只有成对出题，才能把「拿召回换新鲜度」这笔账算清。
 *      这正是之前「评测集盲区」的补救 —— 原来那 39 题里一道都没有。
 *
 *   ② 数字密集题（numeric）
 *      答案是一串精确数字（字节数 / 条数 / 占比 / 行号）。
 *      这类题最容易被「同主题不同结论」的相似文本挤掉，
 *      正好用来压测「排序是不是真按相关性」。
 *
 *   ③ 指代消解题（coref）
 *      问题里不出现原词，只出现「那个东西 / 你说的那个坑」。
 *      考的是「能不能靠上下文找到指代对象」，不是词面匹配。
 *
 *   ④ 跨会话同主题题（cross）
 *      同一个主题在多个会话里都出现过，但**只有一个会话里有确切答案**。
 *      检索被限定在单会话内，所以这题考的是「本会话里到底有没有」。
 *      ——配对的兄弟题放在另一个会话，用来暴露「串会话污染」。
 *
 * ⚠️⚠️⚠️ 造题硬约束（每条都踩过）：
 *   1. gold 必须落在 pri>=1 且 noise=0 的行上，否则默认检索**永远看不到**它。
 *      这不算「题难」，这叫「题错」。写完必须跑 check-cases.js。
 *   2. 每题必须先 probe-show.js 看过原文再标 seq，不能凭印象。
 *      标错不报错，只会让 Recall 凭空下降，然后被误读成检索坏了。
 *   3. 同一结论常有多条等价表述。若只标其中一条，检索命中另一条会被判漏召。
 *      这类题用 minHit:1 + 多 gold 表达「任一条都算对」。
 */
