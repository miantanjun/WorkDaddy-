/* 第四批题：**新鲜度梯度题**（freshness ladder）
 *
 * ── 为什么必须新造这一批 ──────────────────────────────────────
 * 前三批 109 道题的 gold 有一个共同缺陷：**它们基本都是「会话里最新的那条结论」**。
 * 而换位机制依赖的正是「新鲜度差异」—— gold 都一样新鲜，这个信号就被抹平了，
 * 无论换位做得对还是错，测出来的差异都是噪声。
 *
 * 更糟的是上一轮我以为这是「评测集天然盲区」，实际上是**评测自己污染了信号**：
 * 产品 search() 会回写 last_hit_ts = now（ck-memory.js:2027），跑一次评测就把
 * 被测的 gold 全刷成「刚刚命中过」。实测 990 行的 last_hit_ts 被刷新，
 * gold 的 recency 一度全落在 0.998（≈2 小时前），而它们的 ts 中位是 15.3 天前。
 * ⇒ 清零后梯度才真实浮现：p10=0.378 / p50=0.700 / p90=0.976。
 *
 * ── 这批题怎么设计的 ────────────────────────────────────────
 * 找一条**同一指标被反复记录、值随时间单调变化**的真实序列：
 *   回归套件数：41 → 88（跨 42 天，102 条记录，含 3 次真实回落）
 * 然后造**成对题**，只改时间词、不动其余措辞：
 *   问「最新/现在」 ⇒ gold = 最新那行（新鲜度高）⇒ 换位**应该**帮忙
 *   问「最早/一开始」⇒ gold = 最早那行（新鲜度低）⇒ 换位**应该**帮倒忙
 * 这样「新鲜度信号有没有用」就变成一个可观测的因果实验：
 *   若换位真按新鲜度做事，latest 组应显著受益、earliest 组应显著受损。
 *   若两组变化方向一致或都是噪声，那换位就不是在按新鲜度做事。
 *
 * ⚠️ 造题硬约束（每条都踩过）：
 *   · gold 必须 pri>=1 且 noise=0 且 kind in (user,assistant)，否则默认检索永远看不到
 *   · sid 与 seq 必须一起核对（同一个 seq 在不同会话指向完全不同的行）
 *   · 必须先用 probe-show.js 看原文再标 seq，不能凭印象
 * ⚠️ 本批**故意让 gold 的新鲜度两极分化** —— 这正是它的价值所在。
 *   所以它不该和前三批混在一起算总分（会把「新鲜度梯度」这个自变量稀释掉），
 *   必须单独成组统计。
 */
